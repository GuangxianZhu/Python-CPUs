# ─── 每一小步的文字说明 ───

PHASE_NAMES = ["① 取指令", "② 读懂指令", "③ 拿数据", "④ 计算", "⑤ 存结果"]

OP_CN = {"NOP": "什么也不做", "LD": "装数字", "MOV": "复制", "DISP": "显示",
         "XOR": "异或", "AND": "与", "OR": "或", "ADD": "加法", "SUB": "减法"}
AFS_CN = ["异或", "与", "或", "加法"]
SOURCE_CN = ["指令里写的数字", "计算器的结果", "盒子里的数", "盒子里的数"]


def uses(trace):
    """这条指令真正“用到”的通路（其它通路上照样有值，只是没人要）。"""
    c = trace["ctrl"]
    use_alu = bool(c["WE"] and c["RSS"] == 1)
    return {
        "alu": use_alu,
        "A": use_alu or bool(c["WE"] and c["RSS"] >= 2) or bool(c["DWE"]),
        "B": use_alu or bool(c["DWE"]),
        "data": bool(c["WE"] and c["RSS"] == 0),
        "D": bool(c["WE"]),
        "disp": bool(c["DWE"]),
    }


def alu_op_cn(ctrl):
    return "减法" if ctrl["SUB"] else AFS_CN[ctrl["AFS"]]


def meaning(t):
    """用一句话说这条指令要干什么。"""
    f = t["fields"]
    op = MNEMONIC.get(f["opcode"])
    d, a, b = f["D"], f["A"], f["B"]
    if op == "LD":
        return "把数字 {} 放进盒子 R{}".format(f["Data"], d)
    if op == "MOV":
        return "把盒子 R{} 里的数复制到盒子 R{}".format(a, d)
    if op == "DISP":
        return "用盒子 R{} 和 R{} 里的数拼成一个字，显示到屏幕上".format(a, b)
    if op == "ADD":
        return "R{} 加 R{}，结果放进 R{}".format(a, b, d)
    if op == "SUB":
        return "R{} 减 R{}，结果放进 R{}".format(a, b, d)
    if op in ("XOR", "AND", "OR"):
        return "R{} 和 R{} 做“{}”，结果放进 R{}".format(a, b, OP_CN[op], d)
    return "什么也不做"


def describe_phase(t, phase):
    """给初学者看的说明：先说在干嘛，少用术语。"""
    f, c, u, al = t["fields"], t["ctrl"], uses(t), t["alu"]
    op = MNEMONIC.get(f["opcode"])
    if phase == 0:
        return ("① 取指令：书签（PC）指着第 {} 行，CPU 把这一行命令取出来：{}。意思是“{}”。"
                .format(t["pc"], t["text"], meaning(t)))
    if phase == 1:
        if op is None:
            return "② 读懂指令：领班查不到这种命令，于是什么指示都不发，等于“什么也不做”。"
        orders = []
        if c["WE"]:
            src = SOURCE_CN[c["RSS"]]
            if c["RSS"] == 0:
                src += " {} ".format(f["Data"])
            elif c["RSS"] >= 2:
                src = "盒子 R{} 里的数".format(f["A"])
            orders.append("把{}存进盒子 R{}".format(src, f["D"]))
        if u["alu"]:
            orders.append("计算器做{}".format(alu_op_cn(c)))
        if c["DWE"]:
            orders.append("往屏幕上写一个字")
        if not c["WE"]:
            orders.append("这次不往任何盒子里存东西")
        return ("② 读懂指令：前 4 位 {} 代表“{}”。领班（译码器）看懂后向各部件下指示：{}。"
                .format(bits(f["opcode"]), OP_CN[op], "；".join(orders)))
    if phase == 2:
        s = "③ 拿数据：按命令里写的编号，从盒子 R{} 拿出 {}，从盒子 R{} 拿出 {}。".format(
            f["A"], t["a_val"], f["B"], t["b_val"])
        if not (u["A"] or u["B"]):
            s += "这条命令其实用不上它们，但电路每次都会顺手拿出来，没人要就算了。"
        elif not u["B"]:
            s += "这条命令只用得上第一个。"
        if op == "LD":
            s += "要放的数字 {} 就写在命令里，不用去盒子里拿。".format(f["Data"])
        return s
    if phase == 3:
        if not u["alu"]:
            return ("④ 计算：这条命令不需要计算。不过计算器一直通着电，还是把能算的都算了一遍，"
                    "结果没人要，会被扔掉。")
        a, b, r = al["a"], al["b"], al["result"]
        if c["AFS"] == 3:
            raw = a - b if c["SUB"] else a + b
            s = "④ 计算：计算器（ALU）做{}：{} {} {} = {}。".format(
                alu_op_cn(c), a, "−" if c["SUB"] else "+", b, r)
            if raw != r:
                s += "数学上应该是 {}，但盒子只能放 0~15，{}，所以得到 {}（第 7 章讲为什么）。".format(
                    raw, "没有负数" if raw < 0 else "多出来的那一位被丢掉了", r)
            return s
        return "④ 计算：计算器（ALU）做“{}”，一位一位比：{} 和 {} → {}，也就是 {}。".format(
            AFS_CN[c["AFS"]], bits(a), bits(b), bits(r), r)
    if phase == 4:
        if c["WE"]:
            same = "（和原来一样）" if t["old_value"] == t["write_data"] else "（原来是 {}）".format(t["old_value"])
            return ("⑤ 存结果：岔路口选中“{}”，时钟“咔哒”一响，{} 被放进盒子 R{}{}。书签挪到第 {} 行。"
                    .format(SOURCE_CN[c["RSS"]], t["write_data"], f["D"], same, t["pc"] + 1))
        if c["DWE"]:
            return ("⑤ 显示：屏幕上出现字符 '{}'。这次没有改动任何盒子。书签挪到第 {} 行。"
                    .format(display_char(t["disp_code"]), t["pc"] + 1))
        return "⑤ 存结果：什么也不存。书签挪到第 {} 行。".format(t["pc"] + 1)
    return ""


def describe_detail(t, phase):
    """给想深入的同学：原电路里的信号名、二进制和控制字。"""
    f, c, u = t["fields"], t["ctrl"], uses(t)
    if phase == 0:
        return ("PC = {pc}，程序存储器（ROM）输出 16 位指令 0x{code:04X} = {b}。"
                .format(pc=t["pc"], code=t["code"], b=" ".join(bits(t["code"] >> s) for s in (12, 8, 4, 0))))
    if phase == 1:
        return ("opcode = {op}，译码器查表输出 7 位控制字 {w}：WE（写寄存器）={we}，DWE（写显示器）={dwe}，"
                "RSS（写回选择）={rss}，AFS（ALU 功能）={afs}，SUB（减法）={sub}。"
                .format(op=bits(f["opcode"]), w=bits(c["word"], 7), we=c["WE"], dwe=c["DWE"],
                        rss=bits(c["RSS"], 2), afs=bits(c["AFS"], 2), sub=c["SUB"]))
    if phase == 2:
        return ("读端口 A：地址 {A} → R{A} = {ab}；读端口 B：地址 {B} → R{B} = {bb}。"
                "读端口是组合逻辑（8 选 1 MUX），一直在输出。立即数 Data = 指令[3:0] = {d}。"
                .format(A=f["A"], ab=bits(t["a_val"]), B=f["B"], bb=bits(t["b_val"]), d=bits(f["Data"])))
    if phase == 3:
        al = t["alu"]
        cand = al["candidates"]
        s = ("ALU 四路并行：XOR={} AND={} OR={} {}={}，AFS={} 选第 {} 路 → {}。"
             .format(cand[0], cand[1], cand[2], "SUB" if al["sub"] else "ADD", cand[3],
                     bits(al["afs"], 2), al["afs"], al["result"]))
        if al["sub"]:
            s += "减法 = A + (B 按位取反) + 1：{} + {} + 1，进位链 c4..c0 = {}，结果 {}。".format(
                bits(al["a"]), bits(al["b_in"]), "".join(str(x) for x in reversed(al["carries"])),
                bits(al["result"]))
        elif al["afs"] == 3:
            s += "进位链 c4..c0 = {}{}。".format("".join(str(x) for x in reversed(al["carries"])),
                                            "，c4=1 溢出被丢弃" if al["carries"][4] else "")
        return s
    if phase == 4:
        s = "写回 MUX：RSS={} 选第 {} 路（{}）= {}。".format(
            bits(c["RSS"], 2), c["RSS"], RSS_NAMES[c["RSS"]], t["write_data"])
        if c["WE"]:
            s += "时钟上升沿，WE=1，3-8 译码器打开 R{} 的写使能，写入 {}。".format(f["D"], bits(t["write_data"]))
        else:
            s += "WE=0，不写寄存器。"
        if c["DWE"]:
            s += "DWE=1，显示器收到 7 位码 {} = 0x{:02X}（R{} 低 3 位 + R{} 4 位）。".format(
                bits(t["disp_code"], 7), t["disp_code"], f["A"], f["B"])
        return s + "PC ← PC + 1 = {}。".format(t["pc"] + 1)
    return ""


